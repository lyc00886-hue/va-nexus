function read(path: string): string {
  return readFileSync(join(root, path), 'utf8')
}

function messages(file: string): Record<string, string> {
  return JSON.parse(read(file)) as Record<string, string>
}

function hanCount(value: string): number {
  return [...value].filter((ch) => /\p{Script=Han}/u.test(ch)).length
}

function englishWords(value: string): number {
  return value.split(/\s+/).filter((word) => /[A-Za-z0-9]/.test(word)).length
}

describe('research steps preview flag', () => {
  it('stays off unless the query or a stored opt-in says steps', () => {
    assert.equal(researchUxQuery(''), null)
    assert.equal(researchUxQuery('?ux=steps'), 'steps')
    assert.equal(researchUxQuery('ux=off'), 'off')
    assert.equal(researchUxQuery('?ux=preview'), null)

    assert.equal(researchStepsEnabled('', null), false)
    assert.equal(researchStepsEnabled('?foo=1', null), false)
    assert.equal(researchStepsEnabled('?ux=steps', null), true)
    assert.equal(researchStepsEnabled('?ux=steps', 'nope'), true)
    assert.equal(researchStepsEnabled('', 'steps'), true)
    assert.equal(researchStepsEnabled('?ux=classic', 'steps'), false)
    assert.equal(researchStepsEnabled('?ux=off', 'steps'), false)
    assert.equal(researchStepsEnabled('?ux=other', 'steps'), true)

    assert.equal(researchUxPersist('?ux=steps'), 'set')
    assert.equal(researchUxPersist('?ux=classic'), 'clear')
    assert.equal(researchUxPersist('?ux=off'), 'clear')
    assert.equal(researchUxPersist(''), 'keep')
  })

  it('walks the short checklist one item at a time', () => {
    assert.deepEqual(advanceChecklist(0, 3), { index: 1, done: false })
    assert.deepEqual(advanceChecklist(2, 3), { index: 0, done: true })
    assert.deepEqual(advanceChecklist(0, 1), { index: 0, done: true })
    assert.deepEqual(advanceChecklist(0, 0), { index: 0, done: true })
  })

  it('folds a long learning tip and leaves a short one intact', () => {
    assert.deepEqual(splitLearningTip('  Lead line.  '), { lead: 'Lead line.', rest: '' })
    assert.deepEqual(splitLearningTip('Lead\n\nMore detail'), { lead: 'Lead', rest: 'More detail' })
    assert.deepEqual(splitLearningTip('Lead\nsecond'), { lead: 'Lead', rest: 'second' })
    const long = '句'.repeat(90)
    const split = splitLearningTip(long)
    assert.equal(split.lead, `${'句'.repeat(80)}…`)
    assert.equal(split.rest, '句'.repeat(10))
    assert.deepEqual(splitLearningTip(''), { lead: '', rest: '' })
  })
})

describe('research steps copy', () => {
  it('matches the final trilingual short-copy and stays inside the bubble limit', () => {
    const files = {
      en: 'src/i18n/en.json',
      'zh-Hant': 'src/i18n/zh-Hant.json',
      'zh-Hans': 'src/i18n/zh-Hans.json',
    } as const
    for (const locale of Object.keys(files) as (keyof typeof files)[]) {
      const bag = messages(files[locale])
      for (const [key, value] of Object.entries(COPY[locale])) {
        assert.equal(bag[key], value, `${locale} ${key}`)
        if (locale === 'en') assert.ok(englishWords(value) <= 12, value)
        else assert.ok(hanCount(value) <= 18, value)
        for (const banned of BANNED) assert.equal(value.includes(banned), false, `${key} ${banned}`)
      }
      assert.equal(bag['fw.ai.title'], AI_TITLE[locale])
      assert.equal(bag['research.feldmanBench'], AI_TITLE[locale])
      assert.equal(bag['rs.ai.title'], AI_TITLE[locale])
    }
  })

  it('keeps the classic writer as the default and the feedback path untouched', () => {
    const lab = read('src/components/game/ResearchLab.tsx')
    const writer = read('src/components/FeldmanWriter.tsx')
    const shell = read('src/components/game/ResearchStepShell.tsx')
    const feedback = read('api/feedback.ts')

    assert.match(lab, /useResearchStepsShell/)
    assert.match(lab, /shell=\{steps \? 'steps' : undefined\}/)
    assert.match(lab, /steps && getLocale\(\) === 'en' \? t\('lp\.exit'\) : undefined/)
    assert.equal(lab.includes("shell=\"steps\""), false)

    assert.match(writer, /if \(shell === 'steps'\)/)
    assert.match(writer, /t\('fw\.ai\.title'\)/)
    assert.match(writer, /fetch\('\/api\/feedback'/)
    assert.equal(writer.includes('rs.ai.title'), false)

    assert.match(shell, /t\('rs\.ai\.title'\)/)
    assert.match(shell, /t\('rs\.cta\.continue'\)/)
    assert.match(shell, /t\('rs\.cta\.next'\)/)
    assert.match(shell, /t\('rs\.cta\.tip'\)/)
    assert.equal((shell.match(/t\('rs\.back'\)/g) ?? []).length, 1)
    assert.equal((shell.match(/data-research-back/g) ?? []).length, 1)
    assert.equal(shell.includes('/api/feedback'), false)
    assert.equal(shell.includes('fw.ai.title'), false)
    assert.equal(shell.includes('SbaAiFeedback'), false)
    for (const banned of BANNED) assert.equal(shell.includes(banned), false, banned)

    assert.equal(feedback.includes('rs.ai'), false)
    assert.equal(feedback.includes('research-ux'), false)
  })
})
